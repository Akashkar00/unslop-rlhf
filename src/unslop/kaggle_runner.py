"""Run the GPU steps on Kaggle from the terminal.

Only GPU work goes to Kaggle; judge calls stay on your machine, so no API key
ever has to be stored there. Each stage pushes a private script kernel that
clones this repo *at your current pushed commit*, runs the unslop commands,
and tars its outputs; the runner then downloads and unpacks them in place.

    generate:  prompts + candidates            -> data/prompts, data/gen/train_candidates.jsonl
    train:     DPO + tuned/base eval samples   -> outputs/dpo-adapter, data/gen/eval_outputs.jsonl
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import tarfile
import time
from dataclasses import dataclass, field
from pathlib import Path

from .config import Paths

SMOKE_MODEL = "Qwen/Qwen2.5-0.5B-Instruct"
SMOKE_LIMIT = 16
OUT_TAR = "unslop_out.tar.gz"

KERNEL_SCRIPT = '''"""Generated by unslop.kaggle_runner. Do not edit; re-run the runner instead."""
import glob, os, shutil, subprocess, tarfile

CFG = json_cfg

# One T4 is plenty for a 1.5B model, and a single device keeps Trainer away
# from DataParallel, which does not mix well with PEFT + DPO.
os.environ["CUDA_VISIBLE_DEVICES"] = "0"
os.environ["UNSLOP_ROOT"] = ROOT = "/tmp/unslop-run"
os.environ.update(CFG["env"])


def sh(cmd):
    print("+", cmd, flush=True)
    subprocess.run(cmd, shell=True, check=True)


sh(f"git clone -q {CFG['repo']} /tmp/unslop && git -C /tmp/unslop checkout -q {CFG['commit']}")
sh("pip install -q '/tmp/unslop[train]'")
for name, dest in CFG["inputs"].items():
    matches = glob.glob(f"/kaggle/input/**/{name}", recursive=True)
    assert len(matches) == 1, f"expected one {name} under /kaggle/input, found {matches}"
    os.makedirs(os.path.dirname(os.path.join(ROOT, dest)), exist_ok=True)
    shutil.copy(matches[0], os.path.join(ROOT, dest))
for cmd in CFG["commands"]:
    sh(f"python -m unslop.cli {cmd}")
with tarfile.open("/kaggle/working/OUT_TAR", "w:gz") as tar:
    for rel in CFG["outputs"]:
        tar.add(os.path.join(ROOT, rel), arcname=rel)
print("done")
'''


@dataclass(frozen=True)
class Stage:
    name: str
    commands: list[str]
    outputs: list[str]
    # dataset file name -> destination relative to the run root
    inputs: dict[str, str] = field(default_factory=dict)

    def kernel_slug(self) -> str:
        return f"unslop-{self.name}"


def stages(smoke: bool) -> dict[str, Stage]:
    limit = f" --limit {SMOKE_LIMIT}" if smoke else ""
    return {
        "generate": Stage(
            name="generate",
            commands=["prompts", f"generate{limit}"],
            outputs=["data/prompts", "data/gen/train_candidates.jsonl"],
        ),
        "train": Stage(
            name="train",
            commands=["train", f"generate-eval{limit}"],
            outputs=["outputs/dpo-adapter", "data/gen/eval_outputs.jsonl"],
            inputs={"dpo_train.jsonl": "data/pairs/dpo_train.jsonl", "eval.jsonl": "data/prompts/eval.jsonl"},
        ),
    }


class KaggleError(RuntimeError):
    pass


def _kaggle(*args: str, check: bool = True) -> str:
    proc = subprocess.run(["kaggle", *args], capture_output=True, text=True)
    out = "\n".join(line for line in (proc.stdout + proc.stderr).splitlines() if "outdated" not in line)
    if check and proc.returncode != 0:
        raise KaggleError(f"kaggle {' '.join(args)} failed:\n{out}")
    return out


def _git(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", *args], capture_output=True, text=True)


def kaggle_user() -> str:
    if user := os.getenv("UNSLOP_KAGGLE_USER"):
        return user
    match = re.search(r"username:\s*(\S+)", _kaggle("config", "view"))
    if not match:
        raise KaggleError("Couldn't find your Kaggle username; set UNSLOP_KAGGLE_USER.")
    return match.group(1)


def pushed_commit() -> tuple[str, str]:
    """The kernel clones from GitHub, so it can only run code you've pushed."""
    if _git("status", "--porcelain", "--untracked-files=no").stdout.strip():
        raise KaggleError("You have uncommitted changes; Kaggle would run the pushed code, not yours. Commit and push.")
    _git("fetch", "-q", "origin")
    commit = _git("rev-parse", "HEAD").stdout.strip()
    if _git("branch", "-r", "--contains", commit).stdout.strip() == "":
        raise KaggleError(f"Commit {commit[:8]} isn't on GitHub yet. Run `git push` first.")
    url = _git("remote", "get-url", "origin").stdout.strip()
    return url, commit


def push_dataset(user: str, files: dict[str, Path], build: Path) -> str:
    slug = f"{user}/unslop-pairs"
    folder = build / "dataset"
    shutil.rmtree(folder, ignore_errors=True)
    folder.mkdir(parents=True)
    for name, src in files.items():
        shutil.copy(src, folder / name)
    meta = {"title": "unslop-pairs", "id": slug, "licenses": [{"name": "CC-BY-NC-4.0"}]}
    (folder / "dataset-metadata.json").write_text(json.dumps(meta, indent=2))
    exists = "ready" in _kaggle("datasets", "status", slug, check=False).lower()
    if exists:
        _kaggle("datasets", "version", "-p", str(folder), "-m", f"pairs {time.strftime('%Y-%m-%d %H:%M')}", "-q", "-t")
    else:
        _kaggle("datasets", "create", "-p", str(folder), "-q", "-t")  # private by default
    return slug


def wait_dataset(slug: str, timeout: int = 900, poll: int = 15) -> None:
    deadline = time.time() + timeout
    while time.time() < deadline:
        status = _kaggle("datasets", "status", slug, check=False).strip().lower()
        if "ready" in status:
            return
        if "error" in status:
            raise KaggleError(f"dataset {slug} failed to process: {status}")
        time.sleep(poll)
    raise KaggleError(f"dataset {slug} still not ready after {timeout}s")


def push_kernel(user: str, stage: Stage, cfg: dict, build: Path, dataset: str | None) -> str:
    folder = build / stage.name
    shutil.rmtree(folder, ignore_errors=True)
    folder.mkdir(parents=True)
    script = KERNEL_SCRIPT.replace("json_cfg", repr(cfg)).replace("OUT_TAR", OUT_TAR)
    (folder / "run.py").write_text(script)
    meta = {
        "id": f"{user}/{stage.kernel_slug()}",
        "title": stage.kernel_slug(),
        "code_file": "run.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": True,
        "enable_internet": True,
        "machine_shape": "NvidiaTeslaT4",
        "dataset_sources": [dataset] if dataset else [],
        "competition_sources": [],
        "kernel_sources": [],
        "model_sources": [],
    }
    (folder / "kernel-metadata.json").write_text(json.dumps(meta, indent=2))
    out = _kaggle("kernels", "push", "-p", str(folder))
    if "error" in out.lower():
        raise KaggleError(out)
    return meta["id"]


def kernel_status(ref: str) -> str:
    text = _kaggle("kernels", "status", ref).lower()
    for state in ("complete", "error", "cancel", "running", "queued"):
        if state in text:
            return state
    return text.strip()


def wait_kernel(ref: str, poll: int = 60, echo=print) -> str:
    last = None
    while True:
        state = kernel_status(ref)
        if state != last:
            echo(f"[{time.strftime('%H:%M:%S')}] {ref}: {state}")
            last = state
        if state in ("complete", "error", "cancel"):
            return state
        time.sleep(poll)


def fetch(ref: str, paths: Paths, build: Path) -> Path:
    """Download the kernel's outputs and log; unpack outputs into the project."""
    out_dir = build / "output" / ref.split("/")[1]
    shutil.rmtree(out_dir, ignore_errors=True)
    out_dir.mkdir(parents=True)
    _kaggle("kernels", "output", ref, "-p", str(out_dir), "-o", "-q")
    tar_path = out_dir / OUT_TAR
    if tar_path.exists():
        with tarfile.open(tar_path) as tar:
            tar.extractall(paths.root, filter="data")
    return out_dir


def log_tail(out_dir: Path, n: int = 40) -> str:
    logs = sorted(out_dir.glob("*.log"))
    if not logs:
        return "(no log downloaded)"
    raw = logs[0].read_text(errors="replace")
    try:  # Kaggle logs are a JSON array of {stream_name, time, data}
        raw = "".join(entry.get("data", "") for entry in json.loads(raw))
    except (json.JSONDecodeError, AttributeError):
        pass
    return "\n".join(raw.splitlines()[-n:])
