"""Synthetic runs for demonstrating the auditor.

Nothing here is a measurement. Each scenario fabricates eval judgments, outputs
and human labels with a known ground truth, then pushes them through the real
``build_report`` so you can see what the verdict does when a model genuinely
improves and when it only learns to write longer. Files written from here carry
a banner saying so.
"""

from __future__ import annotations

import hashlib
import tempfile
from pathlib import Path

import numpy as np

from .config import Paths
from .io import write_json, write_jsonl
from .metrics import SLOP_PHRASES
from .report import build_report

BANNER = ("> **SYNTHETIC: not a measurement.** Every number below comes from fabricated data generated by "
          "`unslop synthetic-demo` (scenario `{name}`, seed {seed}) to show how the report and verdict behave. "
          "Real results are in [`../results.md`](../results.md).\n\n")

SCENARIOS = {
    # The tuned model is better at any length and a bit tighter; both judges and humans see it.
    "honest": dict(quality=0.9, length_slope=0.3, tuned_len_mult=0.9, train_quality=1.0,
                   slop_base=4.0, slop_tuned=1.5, trunc_base=0.10, trunc_tuned=0.08, human_quality=0.8),
    # The tuned model writes ~1.8x more, and the only "preference" is for length.
    "length_hack": dict(quality=0.0, length_slope=2.5, tuned_len_mult=1.8, train_quality=0.9,
                        slop_base=4.0, slop_tuned=6.0, trunc_base=0.10, trunc_tuned=0.30, human_quality=-0.1),
}

_FILLER = ("the", "a", "and", "of", "to", "in", "it", "that", "we", "you", "when", "with", "for", "is",
           "plan", "garden", "letter", "story", "morning", "river", "coffee", "street", "friend", "window")


def _text(rng: np.random.Generator, words: int, slop_per_1k: float) -> str:
    out = list(rng.choice(_FILLER, size=words))
    for _ in range(rng.poisson(slop_per_1k * words / 1000)):
        out.insert(int(rng.integers(0, len(out) + 1)), str(rng.choice(SLOP_PHRASES)))
    return " ".join(out)


def _sigmoid(x):
    return 1 / (1 + np.exp(-x))


def _verdict(rng: np.random.Generator, p: float) -> tuple[float, bool]:
    """Two position-swapped judge calls with win probability ``p``, scored like PairwiseJudge.compare."""
    s1, s2 = (float(rng.random() < p) for _ in range(2))
    return (s1 + s2) / 2, s1 == s2


def _write_scenario(paths: Paths, cfg: dict, n: int, seed: int) -> None:
    rng = np.random.default_rng(seed)
    base_words = rng.lognormal(np.log(180), 0.4, size=n).astype(int) + 10
    tuned_words = (base_words * cfg["tuned_len_mult"] * rng.lognormal(0, 0.2, size=n)).astype(int) + 5
    log_ratio = np.log(tuned_words / base_words)

    outputs, judgments = [], {"eval": [], "train": []}
    for i in range(n):
        pid = hashlib.sha256(f"synthetic-{seed}-{i}".encode()).hexdigest()
        outputs.append({
            "prompt_id": pid,
            "base": _text(rng, int(base_words[i]), cfg["slop_base"]),
            "tuned": _text(rng, int(tuned_words[i]), cfg["slop_tuned"]),
            "base_finished": bool(rng.random() >= cfg["trunc_base"]),
            "tuned_finished": bool(rng.random() >= cfg["trunc_tuned"]),
        })
        for role, quality in (("eval", cfg["quality"]), ("train", cfg["train_quality"])):
            score, consistent = _verdict(rng, _sigmoid(quality + cfg["length_slope"] * log_ratio[i]))
            judgments[role].append({"prompt_id": pid, "score_tuned": score, "consistent": consistent,
                                    "tuned_words": int(tuned_words[i]), "base_words": int(base_words[i])})

    labels = []
    for i in rng.choice(n, size=min(100, n), replace=False):
        p = _sigmoid(cfg["human_quality"] + 0.3 * log_ratio[i])
        labels.append({"item_id": f"eval:{outputs[i]['prompt_id']}", "kind": "eval",
                       "ref": outputs[i]["prompt_id"], "human_score_x": float(rng.random() < p)})

    write_jsonl(paths.eval_outputs, outputs)
    for role, rows in judgments.items():
        write_jsonl(paths.eval_judgments(role), rows)
    write_json(paths.eval_judge_stats, {role: {"attempted": n} for role in judgments})
    write_jsonl(paths.human_labels, labels)


def run_scenario(name: str, out_dir: Path, judge_models: dict[str, str], n: int = 150, seed: int = 17,
                 n_boot: int = 2000) -> dict:
    with tempfile.TemporaryDirectory() as tmp:
        paths = Paths(Path(tmp))
        _write_scenario(paths, SCENARIOS[name], n, seed)
        results = build_report(paths, judge_models, n_boot=n_boot, seed=seed)
        md = paths.report_md.read_text(encoding="utf-8")
    out_dir.mkdir(parents=True, exist_ok=True)
    md = md.replace("# unslop: results", f"# unslop: SYNTHETIC example ({name})", 1)
    (out_dir / f"{name}.md").write_text(BANNER.format(name=name, seed=seed) + md, encoding="utf-8")
    write_json(out_dir / f"{name}.json", {"synthetic": True, "scenario": name, "seed": seed, **results})
    return results
